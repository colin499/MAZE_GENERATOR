import type { BuildPlan } from '../../layout/plan';
import { PY_INTERPRETER, PY_MCP_TAIL, PY_RUN_ENTRY } from './pyTemplate';

export interface EmitOptions {
  /** 'resume' skips groups whose marker body exists; 'replace' deletes the component first. */
  readonly mode?: 'resume' | 'replace';
  readonly updateParams?: boolean;
}

function header(plan: BuildPlan, opts: Required<EmitOptions>, kind: string): string {
  return [
    `# Generated by ${plan.meta.generator} — ${kind}`,
    `# seed=${plan.meta.seed} topology=${plan.meta.topology}`,
    `# Units: PLAN values are millimetres; expressions reference Fusion user parameters.`,
    `MODE = ${JSON.stringify(opts.mode)}`,
    `UPDATE_PARAMS = ${opts.updateParams ? 'True' : 'False'}`,
    `PLAN = ${pyLiteral(plan)}`,
  ].join('\n');
}

function withDefaults(o: EmitOptions): Required<EmitOptions> {
  return { mode: o.mode ?? 'resume', updateParams: o.updateParams ?? true };
}

/** Single script for Fusion's Scripts & Add-Ins dialog (no bridge timeout; builds everything). */
export function emitFusionScript(plan: BuildPlan, opts: EmitOptions = {}): string {
  const o = withDefaults(opts);
  return `${header(plan, o, 'standalone script')}\n${PY_INTERPRETER}\n${PY_RUN_ENTRY}`;
}

export interface Chunk {
  readonly name: string;
  readonly groups: readonly string[];
  readonly code: string;
}

/**
 * One script per feature group (layer) for the MCP bridge, each self-contained and idempotent so a
 * timed-out or retried call never duplicates geometry. The first chunk uses the requested mode;
 * later chunks always resume.
 */
export function emitFusionChunks(plan: BuildPlan, opts: EmitOptions = {}): Chunk[] {
  const o = withDefaults(opts);
  return plan.groups.map((g, i) => {
    const mode = i === 0 ? o.mode : 'resume';
    const chunkPlan: BuildPlan = { ...plan, groups: [g] };
    const code = `${header(chunkPlan, { ...o, mode }, `chunk ${i + 1}/${plan.groups.length}`)}\nCHUNK_GROUPS = ${JSON.stringify([g.name])}\n${PY_INTERPRETER}\n${PY_MCP_TAIL}`;
    return { name: g.name, groups: [g.name], code };
  });
}

/** JSON is almost a Python literal; fix the three keywords. */
export function pyLiteral(value: unknown): string {
  return JSON.stringify(value).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False').replace(/\bnull\b/g, 'None');
}
